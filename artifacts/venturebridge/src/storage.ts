export function loadDemoData(): DemoData {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return structuredClone(seed);
    const parsed = JSON.parse(raw) as DemoData;
    if (!parsed || !Array.isArray(parsed.ventures) || parsed.ventures.length === 0) {
      return structuredClone(seed);
    }
    return parsed;
  } catch {
    return structuredClone(seed);
  }
}

export function saveDemoData(data: DemoData): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
  } catch {
    // Prototype remains usable when storage is unavailable.
  }
}

export function resetDemoData(): DemoData {
  const fresh = structuredClone(seed);
  saveDemoData(fresh);
  return fresh;
}

export function createVenture(input: Omit<Venture, 'id' | 'status' | 'feedback' | 'createdAt' | 'interests'>): Venture {
  const amt = input.requestedAmount;
  let priceRange = '15-30';
  if (amt <= 5) priceRange = '2-5';
  else if (amt <= 10) priceRange = '5-10';
  else if (amt <= 15) priceRange = '10-15';
  else if (amt <= 30) priceRange = '15-30';
  else if (amt <= 50) priceRange = '30-50';
  else priceRange = '50+';

  return {
    ...input,
    id: `ib-${Date.now().toString().slice(-6)}`,
    status: 'Under review',
    feedback: '',
    createdAt: new Date().toISOString().slice(0, 10),
    interests: [],
    priceRange,
    imageUrl: 'https://images.unsplash.com/photo-1516321318423-f06f85e504b3?w=400&auto=format&fit=crop&q=80',
  };
}
